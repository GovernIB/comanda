package es.caib.comanda.usuaris.logic.intf.model;

import es.caib.comanda.ms.logic.intf.annotation.ResourceAccessConstraint;
import es.caib.comanda.ms.logic.intf.annotation.ResourceArtifact;
import es.caib.comanda.ms.logic.intf.annotation.ResourceConfig;
import es.caib.comanda.ms.logic.intf.annotation.ResourceField;
import es.caib.comanda.ms.logic.intf.model.BaseResource;
import es.caib.comanda.ms.logic.intf.model.ResourceArtifactType;
import es.caib.comanda.ms.logic.intf.permission.PermissionEnum;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.FieldNameConstants;

import javax.persistence.Column;
import javax.validation.constraints.NotNull;
import javax.validation.constraints.Size;
import java.time.LocalDateTime;

@Getter
@Setter
@NoArgsConstructor
@FieldNameConstants
@ResourceConfig(
	descriptionField = "nom",
	accessConstraints = {
		@ResourceAccessConstraint(
			type = ResourceAccessConstraint.ResourceAccessConstraintType.AUTHENTICATED,
			grantedPermissions = { PermissionEnum.READ, PermissionEnum.WRITE }
		)
	},
	artifacts = {
			@ResourceArtifact(type = ResourceArtifactType.PERSPECTIVE, code = Usuari.PERSPECTIVE_PREVIEW_AUTOGENERATED_EMAIL),
	}
)
public class Usuari extends BaseResource<Long> {

	public static final String PERSPECTIVE_PREVIEW_AUTOGENERATED_EMAIL = "PREVIEW_AUTOGENERATED_EMAIL";

    /************************************************ DATOS DEL USUARIO ***********************************************/
    @NotNull @Size(max = 64)
    private String codi;
    @NotNull @Size(max = 255)
    private String nom;
    @Size(max = 10)
    private String nif;
    @Size(max = 255)
    private String email;

    @Size(max = 200)
    private String emailAlternatiu;
    @NotNull
    private LanguageEnum idioma;
    private TemaAplicacioEnum temaAplicacio;
    @NotNull
    private MenuEstilEnum estilMenu;
    private String[] rols;
	private LocalDateTime darreraConnexio = LocalDateTime.now();

    @ResourceField(onChangeActive = true)
    private boolean alarmaMail;
    private boolean alarmaMailAgrupar;

    /************************************************ CONFIGURACIÓN GENÉRICA ******************************************/
    @NotNull
    private NumOfElementsPerPageENum numElementsPagina;
    private AlarmaSoundEnum alarma;

	/************************************************ PERSPECTIVES ****************************************************/
	private String autogeneratedEmail;
}
